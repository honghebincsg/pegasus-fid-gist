func annotateAirport(data map[string]any, code string) map[string]any {
	if data == nil {
		return nil
	}
	if meta, ok := airportMeta[strings.ToUpper(code)]; ok {
		data["airport_name"] = meta.NameCN
		data["airport_name_en"] = meta.NameEN
		data["iata"] = meta.IATA
	}
	return data
}
